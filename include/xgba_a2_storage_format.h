#ifndef GUARD_XGBA_A2_STORAGE_FORMAT_H
#define GUARD_XGBA_A2_STORAGE_FORMAT_H

// A2 on-disk constants, shared by the offline converter and the future game.
// XGBA E6 0x0F extension is byte-access ONLY; no 16/32-bit store/load.
#define XGBA_A2_SAVE_BYTES 0x1000000
#define XGBA_A2_NATIVE_BYTES 0x20000
#define XGBA_A2_PC_BASE 0x200000
#define XGBA_A2_PC_BYTES 34144
#define XGBA_A2_PC_PAGES 8
#define XGBA_A2_PC_BOXES_PER_PAGE 14
#define XGBA_A2_PC_STRIDE 0x9000
#define XGBA_A2_PC_META_BASE 0x290000
#define XGBA_A2_PC_META_STRIDE 0x40
#define XGBA_A2_RECORD_HEADER_BYTES 32
#define XGBA_A2_RECORD_VERSION 1
#define XGBA_A2_GUEST_PC_BASE (0x0F000000 + XGBA_A2_PC_BASE - XGBA_A2_NATIVE_BYTES)
#define XGBA_A2_GUEST_META_BASE (0x0F000000 + XGBA_A2_PC_META_BASE - XGBA_A2_NATIVE_BYTES)

#endif
